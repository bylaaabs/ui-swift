// swift-tools-version: 6.2
// the laaabs. design kit for macOS and iOS. every app imports `LaaabsKit` and nothing else of it.
import PackageDescription

let package = Package(
    name: "LaaabsKit",
    // the words the kit says itself come in english and spanish, as every app does
    defaultLocalization: "en",
    // the lowest the apps ship on: islaaand runs on macOS 14 (speaaak and clipboaaard 15, caaapture
    // and terminaaal 26, baaar and taaab 27); iOS 18 for clipboaaard and finaaance. the kit uses
    // nothing newer, so an app never has to raise its own for it
    platforms: [.macOS(.v14), .iOS(.v18)],
    products: [
        .library(name: "LaaabsKit", targets: ["LaaabsKit"]),
        // the shortcut recorder, apart: only the apps that record shortcuts pull KeyboardShortcuts
        .library(name: "LaaabsShortcuts", targets: ["LaaabsShortcuts"]),
    ],
    dependencies: [
        // the version caaapture pins; an app that uses it pins the same
        .package(url: "https://github.com/sindresorhus/KeyboardShortcuts", exact: "2.4.0"),
    ],
    targets: [
        // the marks, generated by brand from its vectors and compiled as they are: never retyped here
        .target(name: "LaaabsWordmarks", path: "brand/generated/swift"),
        // outfit and geist mono ship inside the kit, so an app no longer needs its own copy
        .target(name: "LaaabsKit", dependencies: ["LaaabsWordmarks"], path: "Sources/LaaabsKit", resources: [.copy("Resources/Fonts"), .process("Resources/en.lproj"), .process("Resources/es.lproj")]),
        .target(
            name: "LaaabsShortcuts",
            dependencies: ["LaaabsKit", .product(name: "KeyboardShortcuts", package: "KeyboardShortcuts")],
            path: "Sources/LaaabsShortcuts"
        ),
        // every component on one screen, to compare against the apps and the pencil canvas
        .executableTarget(name: "Gallery", dependencies: ["LaaabsKit", "LaaabsShortcuts"], path: "Gallery"),
        .testTarget(name: "LaaabsKitTests", dependencies: ["LaaabsKit"], path: "Tests/LaaabsKitTests"),
    ]
)
